"""Recover the exact frozen C0 contract tree from append-only session history.

The original 25-file tree was frozen before it was committed.  Completed
Codex session logs retain the successful post-freeze apply-patch inputs.  This
module starts from the current allowlisted files, reverses every recorded hunk
after the exact digest-computation event, and requires the recovered bytes to
match the independently recorded C0 digest.

Recovery proves byte availability only.  It is generated by the evaluated
system, is not independent review, and grants no contract activation, model,
rating, Draft Score, probability, odds, EV, recommendation, or betting
authority.
"""

