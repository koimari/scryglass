class ContractPriorTreeRecoveryError(RuntimeError):
    """The recovery inputs, transformations, or recovered tree are invalid."""


def _sha256(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _strict_object(raw: bytes, label: str) -> dict[str, Any]:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in items:
            if key in result:
                raise ContractPriorTreeRecoveryError(
                    f"{label} contains duplicate key {key!r}"
                )
            result[key] = value
        return result

    try:
        value = json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=pairs,
            parse_constant=lambda token: (_ for _ in ()).throw(ValueError(token)),
        )
    except ContractPriorTreeRecoveryError:
        raise
    except (UnicodeDecodeError, ValueError, json.JSONDecodeError) as exc:
        raise ContractPriorTreeRecoveryError(f"{label} is not strict JSON") from exc
    if not isinstance(value, dict):
        raise ContractPriorTreeRecoveryError(f"{label} must be an object")
    return value


def _source_record(root: Path) -> dict[str, Any]:
    path = root / SOURCE_LOCATOR
    if path.is_symlink() or not path.is_file():
        raise ContractPriorTreeRecoveryError("recovery source is unavailable")
    raw = path.read_bytes()
    return {
        "locator": SOURCE_LOCATOR,
        "bytes": len(raw),
        "raw_sha256": _sha256(raw),
    }


def _timestamp(value: str) -> datetime:
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        raise ContractPriorTreeRecoveryError("session timestamp lacks timezone")
    return parsed.astimezone(timezone.utc)


def _payload_patch(payload: Mapping[str, Any]) -> str | None:
    name = payload.get("name")
    arguments = payload.get("arguments") or payload.get("input")
    if name == "apply_patch":
        if isinstance(arguments, Mapping):
            value = arguments.get("patch") or arguments.get("input")
            return value if isinstance(value, str) else None
        if isinstance(arguments, str):
            try:
                decoded = json.loads(arguments)
            except json.JSONDecodeError:
                return arguments
            if isinstance(decoded, Mapping):
                value = decoded.get("patch") or decoded.get("input")
                return value if isinstance(value, str) else None
            return arguments
    if not isinstance(arguments, str) or "tools.apply_patch" not in arguments:
        return None
    quoted = re.search(
        r'const patch\s*=\s*("(?:\\.|[^"\\])*")\s*;',
        arguments,
        re.DOTALL,
    )
    if quoted:
        try:
            # Session JSON stores the JavaScript string one layer above the
            # runtime string passed to apply_patch.
            return (
                json.loads(quoted.group(1))
                .replace("\\n", "\n")
                .replace('\\"', '"')
            )
        except json.JSONDecodeError:
            # A tool-call source file can itself contain the literal parser
            # example above. It is not an encoded patch input. Missing a real
            # transformation still makes the final frozen digest fail.
            return None
    template = re.search(
        r"const patch\s*=\s*`([\s\S]*?)`\s*;", arguments
    )
    return template.group(1) if template else None


def _normalize_prime_event(event: dict[str, Any]) -> dict[str, Any] | None:
    """Map a prime-agent session line to the archived codex event shape."""
    if event.get("type") != "message":
        return None
    message = event.get("message")
    if not isinstance(message, dict):
        return None
    role = message.get("role")
    if role == "toolResult":
        call_id = message.get("toolCallId")
        if not isinstance(call_id, str):
            return None
        output = "".join(
            str(part.get("text", ""))
            for part in message.get("content", [])
            if isinstance(part, dict) and "text" in part
        )
        return {
            "timestamp": event.get("timestamp"),
            "payload": {
                "type": "function_call_output",
                "call_id": call_id,
                "output": output,
            },
        }
    if role == "assistant":
        normalized: list[dict[str, Any]] = []
        for part in message.get("content", []):
            if not isinstance(part, dict) or part.get("type") != "toolCall":
                continue
            normalized.append(
                {
                    "timestamp": event.get("timestamp"),
                    "payload": {
                        "type": "function_call",
                        "call_id": part.get("id"),
                        "name": part.get("name"),
                        "arguments": part.get("arguments"),
                    },
                }
            )
        if len(normalized) == 1:
            return normalized[0]
    return None


def _session_events(
    session_root: Path, *, extra_roots: Sequence[Path] = ()
) -> Iterable[tuple[Path, dict[str, Any]]]:
    roots = [session_root, *extra_roots]
    for root in roots:
        if root.is_symlink() or not root.is_dir():
            raise ContractPriorTreeRecoveryError("session root is unavailable")
    for root in roots:
        for path in sorted(root.rglob("*.jsonl")):
            if path.is_symlink() or not path.is_file():
                raise ContractPriorTreeRecoveryError(
                    f"session source is not a regular file: {path}"
                )
            for line_number, line in enumerate(
                path.read_text(encoding="utf-8", errors="strict").splitlines(),
                start=1,
            ):
                try:
                    event = json.loads(line)
                except json.JSONDecodeError:
                    # Some archived output lines were intentionally truncated by
                    # the client. They cannot be transformation inputs and are
                    # ignored; every applied hunk must still resolve exactly once.
                    continue
                if not isinstance(event, dict):
                    raise ContractPriorTreeRecoveryError(
                        f"session event is not an object: {path}:{line_number}"
                    )
                normalized = _normalize_prime_event(event)
                if normalized is not None:
                    event = normalized
                yield path, event


def _verify_cutoff_event(
    events: list[tuple[Path, dict[str, Any]]], session_root: Path
) -> dict[str, Any]:
    expected_path = CUTOFF_SESSION_ROOT / CUTOFF_SESSION_LOCATOR
    call_event: dict[str, Any] | None = None
    output_event: dict[str, Any] | None = None
    for path, event in events:
        payload = event.get("payload") or {}
        if path != expected_path or payload.get("call_id") != CUTOFF_CALL_ID:
            continue
        if payload.get("type") in {"function_call", "custom_tool_call"}:
            call_event = event
        elif payload.get("type") in {
            "function_call_output",
            "custom_tool_call_output",
        }:
            output_event = event
    if call_event is None or output_event is None:
        raise ContractPriorTreeRecoveryError(
            "exact prior-tree digest computation event is unavailable"
        )
    if _timestamp(str(call_event.get("timestamp"))).isoformat() != CUTOFF_UTC:
        raise ContractPriorTreeRecoveryError("cutoff event timestamp changed")
    call_payload = call_event["payload"]
    arguments = call_payload.get("arguments") or call_payload.get("input")
    call_raw = json.dumps(
        arguments, allow_nan=False, ensure_ascii=True, sort_keys=True
    ).encode("ascii")
    output_raw = json.dumps(
        output_event["payload"].get("output"),
        allow_nan=False,
        ensure_ascii=True,
        sort_keys=True,
    ).encode("ascii")
    if validation.CONTRACT_TREE_SHA256 not in output_raw.decode("ascii"):
        raise ContractPriorTreeRecoveryError(
            "cutoff output does not contain the frozen contract digest"
        )
    return {
        "session_locator": CUTOFF_SESSION_LOCATOR,
        "call_id": CUTOFF_CALL_ID,
        "timestamp_utc": CUTOFF_UTC,
        "call_arguments_sha256": _sha256(call_raw),
        "call_output_sha256": _sha256(output_raw),
        "reported_contract_tree_sha256": validation.CONTRACT_TREE_SHA256,
    }


def _patch_sections(patch: str) -> Iterable[tuple[str, list[tuple[list[str], list[str]]]]]:
    sections = re.split(
        r"(?m)^\*\*\* (?=(?:Update|Add|Delete) File: )", patch
    )
    for section in sections:
        match = re.match(
            r"(?:Update|Add|Delete) File: ([^\n]+)\n(.*)",
            section,
            re.DOTALL,
        )
        if not match:
            continue
        locator = match.group(1).strip()
        prefix = f"{ROOT.as_posix()}/"
        if locator.startswith(prefix):
            locator = locator[len(prefix) :]
        try:
            locator = normalize_source_tree_path(locator)
        except Exception:
            continue
        body = match.group(2).split("*** End Patch", 1)[0]
        hunks: list[tuple[list[str], list[str]]] = []
        for hunk in re.split(r"(?m)^@@[^\n]*\n", body)[1:]:
            old: list[str] = []
            new: list[str] = []
            for line in hunk.rstrip("\n").split("\n"):
                if line.startswith("+"):
                    new.append(line[1:])
                elif line.startswith("-"):
                    old.append(line[1:])
                elif line.startswith(" "):
                    old.append(line[1:])
                    new.append(line[1:])
                elif not line.startswith("***"):
                    old.append(line)
                    new.append(line)
            hunks.append((old, new))
        yield locator, hunks


def reconstruct_prior_tree_v1(
    *,
    root: Path = ROOT,
    session_root: Path,
    extra_roots: Sequence[Path] = (),
) -> tuple[dict[str, bytes], dict[str, Any]]:
    allowlist = tuple(validation.CONTRACT_SOURCE_TREE_ALLOWLIST)
    state: dict[str, str] = {}
    for locator in allowlist:
        path = root / locator
        if path.is_symlink() or not path.is_file():
            raise ContractPriorTreeRecoveryError(
                f"current allowlisted source is unavailable: {locator}"
            )
        state[locator] = path.read_text(encoding="utf-8")

    events = list(_session_events(session_root, extra_roots=extra_roots))
    cutoff = _verify_cutoff_event(events, session_root)
    cutoff_time = _timestamp(CUTOFF_UTC)
    patches: list[tuple[datetime, str, str, str]] = []
    for session_path, event in events:
        try:
            event_time = _timestamp(str(event["timestamp"]))
        except (KeyError, ValueError):
            continue
        payload = event.get("payload") or {}
        if (
            event_time <= cutoff_time
            or payload.get("type") not in {"function_call", "custom_tool_call"}
        ):
            continue
        patch = _payload_patch(payload)
        if patch is None:
            continue
        if not any(locator in patch for locator in allowlist):
            continue
        patches.append(
            (
                event_time,
                session_path.relative_to(session_root).as_posix(),
                str(payload.get("call_id") or payload.get("id")),
                patch,
            )
        )

    reversed_hunks: list[dict[str, Any]] = []
    for event_time, session_locator, call_id, patch in sorted(
        patches, key=lambda item: item[0], reverse=True
    ):
        patch_sha256 = _sha256(patch.encode("utf-8"))
        for locator, hunks in reversed(list(_patch_sections(patch))):
            if locator not in state:
                continue
            for reverse_index, (old, new) in enumerate(reversed(hunks)):
                new_block = "\n".join(new)
                old_block = "\n".join(old)
                matches = state[locator].count(new_block) if new_block else 0
                if matches != 1:
                    raise ContractPriorTreeRecoveryError(
                        "recorded reverse hunk does not resolve exactly once: "
                        f"{locator} {call_id} matches={matches}"
                    )
                state[locator] = state[locator].replace(
                    new_block, old_block, 1
                )
                reversed_hunks.append(
                    {
                        "timestamp_utc": event_time.isoformat(),
                        "session_locator": session_locator,
                        "call_id": call_id,
                        "patch_sha256": patch_sha256,
                        "locator": locator,
                        "reverse_hunk_index": reverse_index,
                        "post_hunk_sha256": _sha256(
                            state[locator].encode("utf-8")
                        ),
                    }
                )

    recovered = {
        locator: state[locator].encode("utf-8") for locator in allowlist
    }
    digest = hashlib.sha256()
    digest.update(PREFIX)
    for locator in sorted(recovered):
        path_raw = locator.encode("utf-8")
        content = recovered[locator]
        digest.update(len(path_raw).to_bytes(8, "big", signed=False))
        digest.update(path_raw)
        digest.update(len(content).to_bytes(8, "big", signed=False))
        digest.update(content)
    if digest.hexdigest() != validation.CONTRACT_TREE_SHA256:
        raise ContractPriorTreeRecoveryError(
            "recovered source tree does not match frozen C0"
        )
    evidence = {
        "cutoff_evidence": cutoff,
        "patch_calls_considered": len(patches),
        "reversed_hunk_count": len(reversed_hunks),
        "reversed_hunks": list(reversed(reversed_hunks)),
    }
    return recovered, evidence


def _manifest_payload(
    *,
    root: Path,
    recovered: Mapping[str, bytes],
    evidence: Mapping[str, Any],
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "result_state": RESULT_STATE,
        "evidence_root": DEFAULT_EVIDENCE_ROOT.as_posix(),
        "contract_tree_sha256": validation.CONTRACT_TREE_SHA256,
        "allowlist": list(validation.CONTRACT_SOURCE_TREE_ALLOWLIST),
        "file_raw_sha256": {
            locator: _sha256(raw)
            for locator, raw in sorted(recovered.items())
        },
        "file_count": len(recovered),
        "reconstruction": dict(evidence),
        "runner_provenance": {
            "generated_by_evaluated_system": True,
            "independent_review_eligible": False,
            "source_lock": _source_record(root),
        },
        "authority": dict(AUTHORITY),
        "claim_ceiling": CLAIM_CEILING,
    }
    payload["artifact_sha256"] = canonical_sha256(payload)
    return payload


def validate_prior_tree_recovery_v1(
    payload: Mapping[str, Any], *, root: Path = ROOT
) -> dict[str, Any]:
    if not isinstance(payload, Mapping):
        raise ContractPriorTreeRecoveryError("recovery manifest must be an object")
    value = dict(payload)
    expected_keys = {
        "schema_version",
        "result_state",
        "evidence_root",
        "contract_tree_sha256",
        "allowlist",
        "file_raw_sha256",
        "file_count",
        "reconstruction",
        "runner_provenance",
        "authority",
        "claim_ceiling",
        "artifact_sha256",
    }
    if set(value) != expected_keys:
        raise ContractPriorTreeRecoveryError("recovery manifest fields changed")
    if (
        value.get("schema_version") != SCHEMA_VERSION
        or value.get("result_state") != RESULT_STATE
        or value.get("evidence_root") != DEFAULT_EVIDENCE_ROOT.as_posix()
        or value.get("contract_tree_sha256") != validation.CONTRACT_TREE_SHA256
        or value.get("allowlist")
        != list(validation.CONTRACT_SOURCE_TREE_ALLOWLIST)
        or value.get("file_count")
        != len(validation.CONTRACT_SOURCE_TREE_ALLOWLIST)
    ):
        raise ContractPriorTreeRecoveryError("recovery manifest identity changed")
    unsigned = {key: item for key, item in value.items() if key != "artifact_sha256"}
    if value.get("artifact_sha256") != canonical_sha256(unsigned):
        raise ContractPriorTreeRecoveryError("recovery artifact hash changed")
    evidence_root = root / DEFAULT_EVIDENCE_ROOT
    if evidence_root.is_symlink() or not evidence_root.is_dir():
        raise ContractPriorTreeRecoveryError("recovered evidence root is unavailable")
    expected_hashes = value.get("file_raw_sha256")
    if not isinstance(expected_hashes, Mapping):
        raise ContractPriorTreeRecoveryError("recovered file hashes are missing")
    actual_hashes: dict[str, str] = {}
    for locator in validation.CONTRACT_SOURCE_TREE_ALLOWLIST:
        path = evidence_root / locator
        if path.is_symlink() or not path.is_file():
            raise ContractPriorTreeRecoveryError(
                f"recovered file is unavailable: {locator}"
            )
        actual_hashes[locator] = _sha256(path.read_bytes())
    if dict(expected_hashes) != dict(sorted(actual_hashes.items())):
        raise ContractPriorTreeRecoveryError("recovered file hashes changed")
    if (
        canonical_source_tree_sha256(
            evidence_root, validation.CONTRACT_SOURCE_TREE_ALLOWLIST
        )
        != validation.CONTRACT_TREE_SHA256
    ):
        raise ContractPriorTreeRecoveryError("recovered tree hash changed")
    runner = value.get("runner_provenance")
    if runner != {
        "generated_by_evaluated_system": True,
        "independent_review_eligible": False,
        "source_lock": _source_record(root),
    }:
        raise ContractPriorTreeRecoveryError("recovery provenance changed")
    reconstruction = value.get("reconstruction")
    if (
        not isinstance(reconstruction, Mapping)
        or reconstruction.get("cutoff_evidence", {}).get(
            "reported_contract_tree_sha256"
        )
        != validation.CONTRACT_TREE_SHA256
        or reconstruction.get("reversed_hunk_count") != 0
        or len(reconstruction.get("reversed_hunks") or []) != 0
    ):
        raise ContractPriorTreeRecoveryError("reconstruction evidence changed")
    if value.get("authority") != AUTHORITY or any(value["authority"].values()):
        raise ContractPriorTreeRecoveryError("recovery exceeds authority")
    if value.get("claim_ceiling") != CLAIM_CEILING:
        raise ContractPriorTreeRecoveryError("recovery claim ceiling changed")
    return value


def write_prior_tree_recovery_v1(
    *,
    root: Path = ROOT,
    session_root: Path,
    extra_roots: Sequence[Path] = (),
) -> tuple[Path, Path]:
    destination = root / DEFAULT_EVIDENCE_ROOT
    manifest_path = root / DEFAULT_MANIFEST
    if destination.exists() or manifest_path.exists():
        raise ContractPriorTreeRecoveryError(
            "refusing to overwrite prior-tree recovery evidence"
        )
    recovered, evidence = reconstruct_prior_tree_v1(
        root=root, session_root=session_root, extra_roots=extra_roots
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = Path(
        tempfile.mkdtemp(prefix=".prior-contract-tree-v1.", dir=destination.parent)
    )
    try:
        for locator, raw in recovered.items():
            path = temporary / locator
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
        if canonical_source_tree_sha256(
            temporary, validation.CONTRACT_SOURCE_TREE_ALLOWLIST
        ) != validation.CONTRACT_TREE_SHA256:
            raise ContractPriorTreeRecoveryError(
                "temporary recovered tree failed exact verification"
            )
        if destination.exists():
            raise ContractPriorTreeRecoveryError(
                "refusing to overwrite prior-tree recovery evidence"
            )
        os.replace(temporary, destination)
    finally:
        if temporary.exists():
            for path in sorted(temporary.rglob("*"), reverse=True):
                if path.is_file():
                    path.unlink()
                elif path.is_dir():
                    path.rmdir()
            temporary.rmdir()
    payload = _manifest_payload(root=root, recovered=recovered, evidence=evidence)
    raw = (
        json.dumps(payload, allow_nan=False, ensure_ascii=True, indent=2, sort_keys=True)
        + "\n"
    ).encode("ascii")
    descriptor, temporary_manifest = tempfile.mkstemp(
        prefix=f".{manifest_path.name}.",
        suffix=".partial",
        dir=manifest_path.parent,
    )
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        if manifest_path.exists():
            raise ContractPriorTreeRecoveryError(
                "refusing to overwrite prior-tree recovery manifest"
            )
        os.replace(temporary_manifest, manifest_path)
    finally:
        if os.path.exists(temporary_manifest):
            os.unlink(temporary_manifest)
    validate_prior_tree_recovery_v1(payload, root=root)
    return destination, manifest_path


def load_prior_tree_recovery_v1(*, root: Path = ROOT) -> dict[str, Any]:
    path = root / DEFAULT_MANIFEST
    if path.is_symlink() or not path.is_file():
        raise ContractPriorTreeRecoveryError("recovery manifest is unavailable")
    return validate_prior_tree_recovery_v1(
        _strict_object(path.read_bytes(), "recovery manifest"), root=root
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--session-root", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.write:
            evidence_root, manifest = write_prior_tree_recovery_v1(
                root=args.root, session_root=args.session_root
            )
            print(
                json.dumps(
                    {
                        "evidence_root": str(evidence_root),
                        "manifest": str(manifest),
                        "manifest_raw_sha256": _sha256(manifest.read_bytes()),
                    },
                    sort_keys=True,
                )
            )
        else:
            recovered, evidence = reconstruct_prior_tree_v1(
                root=args.root, session_root=args.session_root
            )
            print(
                json.dumps(
                    _manifest_payload(
                        root=args.root,
                        recovered=recovered,
                        evidence=evidence,
                    ),
                    indent=2,
                    sort_keys=True,
                )
            )
    except (OSError, ValueError, ContractPriorTreeRecoveryError) as exc:
        print(str(exc))
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


