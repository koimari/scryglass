"""Reference semantic replay for a drifted contract candidate.

This runner proves that the current contract bytes can execute the frozen
five-output semantic harness under explicit candidate anchors.  Because this
module is part of the evaluated repository, its report is reference evidence
only: it is never independent review and cannot activate a trust root or grant
model, rating, Draft Score, probability, odds, EV, recommendation, or betting
authority.
"""

from __future__ import annotations

import argparse
from copy import deepcopy
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import tempfile
from typing import Any, Callable, Mapping

from . import contract_validation as validation
from .types import canonical_sha256


ROOT = Path(__file__).resolve().parents[3]
SOURCE_LOCATOR = (
    "lol_kills/v2/evaluation/contract_reconciliation_semantic_replay_v1.py"
)
VALIDATOR_SOURCE_LOCATOR = "lol_kills/v2/evaluation/contract_validation.py"
SCHEMA_VERSION = (
    "scryglass:contract-validation-reference-semantic-replay:v1"
)
RESULT_STATE = "CANDIDATE_ANCHOR_SEMANTIC_REPLAY_PASSED_REFERENCE_ONLY"
DEFAULT_OUTPUT = Path(
    "data/lol/v2/evaluation/"
    "contract-validation-reference-semantic-replay-v1.json"
)
AUTHORITY = {
    "independent_review_authority": False,
    "contract_trust_root_authority": False,
    "production_model_authority": False,
    "player_rating_authority": False,
    "team_rating_authority": False,
    "draft_validation_authority": False,
    "probability_authority": False,
    "odds_authority": False,
    "expected_value_authority": False,
    "recommendation_authority": False,
    "betting_authority": False,
}
CLAIM_CEILING = (
    "Deterministic in-repository reference replay against current candidate "
    "anchors only. This evidence is generated by the evaluated system, is "
    "not independent review, does not change the active trust root, and "
    "grants no model, rating, Draft Score, probability, odds, expected-value, "
    "recommendation, or betting authority."
)


class ContractSemanticReplayError(RuntimeError):
    """Candidate-anchor semantic replay input or output is invalid."""


def _sha256(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _json_bytes(value: Mapping[str, Any]) -> bytes:
    return (
        json.dumps(
            value,
            allow_nan=False,
            ensure_ascii=True,
            indent=2,
            sort_keys=True,
        )
        + "\n"
    ).encode("ascii")


def _source_record(root: Path, locator: str) -> dict[str, Any]:
    path = root / locator
    if path.is_symlink() or not path.is_file():
        raise ContractSemanticReplayError(f"source is unavailable: {locator}")
    raw = path.read_bytes()
    return {"locator": locator, "bytes": len(raw), "raw_sha256": _sha256(raw)}


def _clock(clock: Callable[[], datetime]) -> datetime:
    value = clock()
    if not isinstance(value, datetime) or value.tzinfo is None:
        raise ContractSemanticReplayError("clock must be timezone-aware")
    return value.astimezone(timezone.utc)


def _current_contract_inputs(root: Path) -> dict[str, Any]:
    contract_root = root / validation.CONTRACT_ROOT
    schema_hashes = {
        name: _sha256((contract_root / name).read_bytes())
        for name in validation.SCHEMA_FILES
    }
    example_hashes = {
        name: _sha256((contract_root / name).read_bytes())
        for name in validation.EXAMPLE_FILES.values()
    }
    semantic_path = root / validation.SEMANTIC_ARTIFACT_PATH
    return {
        "contract_tree_sha256": validation._actual_contract_tree_sha256(root),
        "contract_content_sha256": validation._contract_content_sha256(
            root / validation.CONTRACT_PACK_ROOT
        ),
        "schema_raw_sha256": dict(sorted(schema_hashes.items())),
        "example_raw_sha256": dict(sorted(example_hashes.items())),
        "semantic_artifact_locator": (
            validation.SEMANTIC_ARTIFACT_PATH.as_posix()
        ),
        "semantic_artifact_raw_sha256": _sha256(semantic_path.read_bytes()),
    }


def _candidate_fixture_authority(
    root: Path, contract_tree_sha256: str
) -> dict[str, Any]:
    contract_root = root / validation.CONTRACT_ROOT
    authority = json.loads(
        (root / validation.CONTRACT_FIXTURE_AUTHORITY_PATH).read_text(
            encoding="utf-8"
        )
    )
    derived: dict[str, list[dict[str, str]]] = {}
    for output in validation.OUTPUT_SCHEMAS:
        entries: list[dict[str, str]] = []
        canonical = json.loads(
            (contract_root / validation.EXAMPLE_FILES[output]).read_text(
                encoding="utf-8"
            )
        )
        entries.append(
            {
                "status": str(canonical["status"]),
                "sha256": validation.canonical_unsigned_output_sha256(
                    canonical
                ),
            }
        )
        if output == "partial_draft_state":
            partial_schema = json.loads(
                (
                    contract_root / validation.OUTPUT_SCHEMAS[output]
                ).read_text(encoding="utf-8")
            )
            for document in partial_schema.get("examples", []):
                entries.append(
                    {
                        "status": str(document["status"]),
                        "sha256": validation.canonical_unsigned_output_sha256(
                            document
                        ),
                    }
                )
        for required_status in ("missing", "stale", "conflict"):
            document = validation._registered_unavailable_fixture(
                output, required_status, contract_root
            )
            entries.append(
                {
                    "status": f"unavailable:{required_status}",
                    "sha256": validation.canonical_unsigned_output_sha256(
                        document
                    ),
                }
            )
        derived[output] = entries
    authority["contract_tree_sha256"] = contract_tree_sha256
    authority["examples"] = {
        name: _sha256((contract_root / name).read_bytes())
        for name in validation.EXAMPLE_FILES.values()
    }
    authority["allowed_unsigned_output_sha256"] = derived
    authority["production_model_authority"] = {
        "status": "fail_closed",
        "reason": (
            "candidate-anchor fixture identities are reference-only and no "
            "production model authority is registered"
        ),
    }
    return authority


def _candidate_trust_root(
    root: Path, contract_tree_sha256: str
) -> dict[str, Any]:
    trust = json.loads(
        (root / validation.CONTRACT_VALIDATION_TRUST_ROOT_PATH).read_text(
            encoding="utf-8"
        )
    )
    trust["contract_tree_sha256"] = contract_tree_sha256
    trust["production_model_authority"] = {
        "status": "fail_closed",
        "missing_layers": ["L4", "L5", "L6", "L9"],
    }
    return trust


def _coverage(root: Path, report: validation.FiveOutputValidationReport) -> dict[str, Any]:
    schemas = {
        name: json.loads(
            (root / validation.CONTRACT_ROOT / name).read_text(encoding="utf-8")
        )
        for name in validation.SCHEMA_FILES
    }
    invariants, mutations = validation._collect_extensions(schemas)
    structural = sorted(
        mutation_id
        for mutation_id, (_, fixture) in mutations.items()
        if fixture.get("expected_schema_failure") is True
    )
    return {
        "outputs": sorted(validation.OUTPUT_SCHEMAS),
        "invariant_ids": sorted(invariants),
        "mutation_ids": sorted(mutations),
        "structural_mutation_ids": structural,
        "invariant_pass_count": report.invariant_pass_count,
        "mutation_pass_count": report.mutation_pass_count,
        "canonical_structural_pass_count": report.structural_pass_count,
        "structural_mutation_pass_count": len(structural),
        "all_pass": report.all_pass,
    }


def _execute_candidate_replay(root: Path) -> tuple[
    dict[str, Any], validation.FiveOutputValidationReport
]:
    inputs = _current_contract_inputs(root)
    with tempfile.TemporaryDirectory(prefix="scryglass-contract-replay-") as tmp:
        temporary_root = Path(tmp)
        fixture_path = temporary_root / "candidate-fixture-authority.json"
        trust_path = temporary_root / "candidate-trust-root.json"
        fixture_raw = _json_bytes(
            _candidate_fixture_authority(root, inputs["contract_tree_sha256"])
        )
        trust_raw = _json_bytes(
            _candidate_trust_root(root, inputs["contract_tree_sha256"])
        )
        fixture_path.write_bytes(fixture_raw)
        trust_path.write_bytes(trust_raw)
        fixture_payload = json.loads(fixture_raw)
        trust_payload = json.loads(trust_raw)
        anchors = validation.ContractValidationAnchors(
            contract_tree_sha256=inputs["contract_tree_sha256"],
            schema_sha256=inputs["schema_raw_sha256"],
            example_sha256=inputs["example_raw_sha256"],
            semantic_artifact_path=validation.SEMANTIC_ARTIFACT_PATH,
            semantic_artifact_raw_sha256=inputs[
                "semantic_artifact_raw_sha256"
            ],
            contract_fixture_authority_path=fixture_path,
            contract_fixture_authority_raw_sha256=_sha256(fixture_raw),
            contract_fixture_authority_object_sha256=canonical_sha256(
                fixture_payload
            ),
            contract_validation_trust_root_path=trust_path,
            contract_validation_trust_root_raw_sha256=_sha256(trust_raw),
            contract_validation_trust_root_object_sha256=canonical_sha256(
                trust_payload
            ),
            contract_content_sha256=inputs["contract_content_sha256"],
        )
        report = validation.run_five_output_validation(
            repository_root=root,
            contract_root=root / validation.CONTRACT_ROOT,
            anchors=anchors,
        )
        validation.verify_five_output_validation_report(
            report,
            repository_root=root,
            contract_root=root / validation.CONTRACT_ROOT,
            anchors=anchors,
        )
        validation._contract_fixture_identity_pairs(
            root / validation.CONTRACT_ROOT,
            repository_root=root,
            anchors=anchors,
        )
    return inputs, report


def build_reference_semantic_replay_v1(
    *,
    root: Path = ROOT,
    clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc),
) -> dict[str, Any]:
    inputs, report = _execute_candidate_replay(root)
    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "result_state": RESULT_STATE,
        "report_id": "contract-validation-reference-semantic-replay-v1",
        "executed_at_utc": _clock(clock).isoformat(),
        "contract_inputs": inputs,
        "runner_provenance": {
            "implementation_id": (
                "scryglass-in-repository-reference-runner-v1"
            ),
            "generated_by_evaluated_system": True,
            "independent_review_eligible": False,
            "source_locks": [
                _source_record(root, SOURCE_LOCATOR),
                _source_record(root, VALIDATOR_SOURCE_LOCATOR),
            ],
        },
        "five_output_report": report.to_payload(),
        "coverage": _coverage(root, report),
        "authority": dict(AUTHORITY),
        "claim_ceiling": CLAIM_CEILING,
    }
    payload["artifact_sha256"] = canonical_sha256(payload)
    return validate_reference_semantic_replay_v1(payload, root=root)


def validate_reference_semantic_replay_v1(
    payload: Mapping[str, Any], *, root: Path = ROOT
) -> dict[str, Any]:
    if not isinstance(payload, Mapping):
        raise ContractSemanticReplayError("reference replay must be an object")
    value = deepcopy(dict(payload))
    expected_keys = {
        "schema_version",
        "result_state",
        "report_id",
        "executed_at_utc",
        "contract_inputs",
        "runner_provenance",
        "five_output_report",
        "coverage",
        "authority",
        "claim_ceiling",
        "artifact_sha256",
    }
    if set(value) != expected_keys:
        raise ContractSemanticReplayError("reference replay fields changed")
    if (
        value.get("schema_version") != SCHEMA_VERSION
        or value.get("result_state") != RESULT_STATE
        or value.get("report_id")
        != "contract-validation-reference-semantic-replay-v1"
    ):
        raise ContractSemanticReplayError("reference replay identity changed")
    try:
        executed = datetime.fromisoformat(
            str(value.get("executed_at_utc")).replace("Z", "+00:00")
        )
    except ValueError as exc:
        raise ContractSemanticReplayError(
            "reference replay timestamp is invalid"
        ) from exc
    if executed.tzinfo is None:
        raise ContractSemanticReplayError(
            "reference replay timestamp lacks timezone"
        )
    unsigned = {key: item for key, item in value.items() if key != "artifact_sha256"}
    if value.get("artifact_sha256") != canonical_sha256(unsigned):
        raise ContractSemanticReplayError("reference replay artifact hash changed")
    if value.get("contract_inputs") != _current_contract_inputs(root):
        raise ContractSemanticReplayError("reference replay inputs drifted")
    runner = value.get("runner_provenance")
    if runner != {
        "implementation_id": "scryglass-in-repository-reference-runner-v1",
        "generated_by_evaluated_system": True,
        "independent_review_eligible": False,
        "source_locks": [
            _source_record(root, SOURCE_LOCATOR),
            _source_record(root, VALIDATOR_SOURCE_LOCATOR),
        ],
    }:
        raise ContractSemanticReplayError("reference runner provenance changed")
    report_payload = value.get("five_output_report")
    if not isinstance(report_payload, Mapping):
        raise ContractSemanticReplayError("five-output report is missing")
    if (
        report_payload.get("contract_tree_sha256")
        != value["contract_inputs"]["contract_tree_sha256"]
        or report_payload.get("schema_sha256")
        != value["contract_inputs"]["schema_raw_sha256"]
        or report_payload.get("example_sha256")
        != value["contract_inputs"]["example_raw_sha256"]
        or report_payload.get("contract_content_sha256")
        != value["contract_inputs"]["contract_content_sha256"]
        or report_payload.get("semantic_artifact_sha256")
        != value["contract_inputs"]["semantic_artifact_raw_sha256"]
        or report_payload.get("all_pass") is not True
    ):
        raise ContractSemanticReplayError("five-output report binding changed")
    report_unsigned = {
        key: item for key, item in report_payload.items() if key != "report_sha256"
    }
    if report_payload.get("report_sha256") != canonical_sha256(report_unsigned):
        raise ContractSemanticReplayError("five-output report hash changed")
    expected_coverage = {
        "outputs": sorted(validation.OUTPUT_SCHEMAS),
        "invariant_ids": list(report_payload.get("invariant_ids", [])),
        "mutation_ids": list(report_payload.get("mutation_ids", [])),
        "structural_mutation_ids": sorted(
            validation.EXPECTED_STRUCTURAL_DIAGNOSTIC_SHA256
        ),
        "invariant_pass_count": report_payload.get("invariant_pass_count"),
        "mutation_pass_count": report_payload.get("mutation_pass_count"),
        "canonical_structural_pass_count": report_payload.get(
            "structural_pass_count"
        ),
        "structural_mutation_pass_count": len(
            validation.EXPECTED_STRUCTURAL_DIAGNOSTIC_SHA256
        ),
        "all_pass": True,
    }
    if value.get("coverage") != expected_coverage:
        raise ContractSemanticReplayError("reference replay coverage changed")
    if value.get("authority") != AUTHORITY or any(value["authority"].values()):
        raise ContractSemanticReplayError("reference replay exceeds authority")
    if value.get("claim_ceiling") != CLAIM_CEILING:
        raise ContractSemanticReplayError("reference replay claim ceiling changed")
    return value


def replay_matches_reference_semantic_report_v1(
    payload: Mapping[str, Any], *, root: Path = ROOT
) -> bool:
    """Run the harness again and compare all deterministic replay fields."""

    reference = validate_reference_semantic_replay_v1(payload, root=root)
    inputs, report = _execute_candidate_replay(root)
    return (
        reference["contract_inputs"] == inputs
        and reference["five_output_report"] == report.to_payload()
        and reference["coverage"] == _coverage(root, report)
    )


def write_reference_semantic_replay_v1(
    *, root: Path = ROOT, output: Path = DEFAULT_OUTPUT
) -> Path:
    path = output if output.is_absolute() else root / output
    if path.exists():
        raise ContractSemanticReplayError(
            f"refusing to overwrite reference replay: {path}"
        )
    raw = _json_bytes(build_reference_semantic_replay_v1(root=root))
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".partial", dir=path.parent
    )
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        if path.exists():
            raise ContractSemanticReplayError(
                f"refusing to overwrite reference replay: {path}"
            )
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.write:
            path = write_reference_semantic_replay_v1(root=args.root)
            print(
                json.dumps(
                    {"output": str(path), "raw_sha256": _sha256(path.read_bytes())},
                    sort_keys=True,
                )
            )
        else:
            print(
                json.dumps(
                    build_reference_semantic_replay_v1(root=args.root),
                    indent=2,
                    sort_keys=True,
                )
            )
    except (OSError, ValueError, ContractSemanticReplayError) as exc:
        print(str(exc))
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


