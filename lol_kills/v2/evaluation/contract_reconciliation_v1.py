SOURCE_LOCATOR = "lol_kills/v2/evaluation/contract_reconciliation_v1.py"
VALIDATOR_SOURCE_LOCATOR = "lol_kills/v2/evaluation/contract_validation.py"
SCHEMA_VERSION = "scryglass:contract-validation-reconciliation-candidate:v3"
RESULT_STATE = (
    "CURRENT_CONTRACT_BYTES_SEMANTICALLY_REPLAYED_REFERENCE_ONLY_"
    "PENDING_INDEPENDENT_REVIEW"
)
DEFAULT_OUTPUT = Path(
    "data/lol/v2/evaluation/contract-validation-reconciliation-candidate-v3.json"
)
REVIEW_REGISTRY_LOCATOR = Path(
    "data/lol/private_contract_authority/"
    "contract-validation-reconciliation-review-v1.json"
)
REVIEW_REGISTRY_ENV = (
    "SCRYGLASS_CONTRACT_VALIDATION_RECONCILIATION_REVIEW_SHA256"
)
AUTHORITY = {
    "contract_trust_root_authority": False,
    "model_validation_authority": False,
    "player_rating_authority": False,
    "team_rating_authority": False,
    "draft_validation_authority": False,
    "probability_authority": False,
    "odds_authority": False,
    "expected_value_authority": False,
    "recommendation_authority": False,
    "betting_authority": False,
}
CLAIM_CEILING = (
    "Current contract-byte inventory, structural replay, and deterministic "
    "in-repository semantic reference replay only. The reference replay is "
    "generated by the evaluated system and is not independent review. The "
    "active trust root remains unchanged; model authority, probability, odds, "
    "expected value, recommendations, and betting remain unavailable."
)


class ContractReconciliationError(RuntimeError):
    """Current contract bytes or the reconciliation candidate are invalid."""


def _sha256(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _source_record(root: Path, locator: str) -> dict[str, Any]:
    path = root / locator
    if path.is_symlink() or not path.is_file():
        raise ContractReconciliationError(f"source is unavailable: {locator}")
    raw = path.read_bytes()
    return {"locator": locator, "bytes": len(raw), "raw_sha256": _sha256(raw)}


def _clock(clock: Callable[[], datetime]) -> datetime:
    value = clock()
    if not isinstance(value, datetime) or value.tzinfo is None:
        raise ContractReconciliationError("clock must be timezone-aware")
    return value.astimezone(timezone.utc)


def _strict_object(raw: bytes, label: str) -> dict[str, Any]:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in items:
            if key in result:
                raise ContractReconciliationError(
                    f"{label} contains duplicate key {key!r}"
                )
            result[key] = value
        return result

    try:
        value = json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=pairs,
            parse_constant=lambda token: (_ for _ in ()).throw(ValueError(token)),
        )
    except ContractReconciliationError:
        raise
    except (UnicodeDecodeError, ValueError, json.JSONDecodeError) as exc:
        raise ContractReconciliationError(f"{label} is not strict JSON") from exc
    if not isinstance(value, dict):
        raise ContractReconciliationError(f"{label} must contain an object")
    return value


def _reference_semantic_replay(root: Path) -> dict[str, Any]:
    path = root / REFERENCE_REPLAY_LOCATOR
    if path.is_symlink() or not path.is_file():
        raise ContractReconciliationError(
            "reference semantic replay is unavailable"
        )
    raw = path.read_bytes()
    try:
        replay = validate_reference_semantic_replay_v1(
            _strict_object(raw, "reference semantic replay"), root=root
        )
    except ContractSemanticReplayError as exc:
        raise ContractReconciliationError(str(exc)) from exc
    if (
        replay["five_output_report"].get("all_pass") is not True
        or replay["coverage"].get("all_pass") is not True
        or replay["runner_provenance"].get("generated_by_evaluated_system")
        is not True
        or replay["runner_provenance"].get("independent_review_eligible")
        is not False
        or any(replay["authority"].values())
    ):
        raise ContractReconciliationError(
            "reference semantic replay exceeds its evidence boundary"
        )
    return {
        "locator": REFERENCE_REPLAY_LOCATOR.as_posix(),
        "raw_sha256": _sha256(raw),
        "artifact_sha256": replay["artifact_sha256"],
        "executed_at_utc": replay["executed_at_utc"],
        "five_output_report_sha256": replay["five_output_report"][
            "report_sha256"
        ],
        "contract_tree_sha256": replay["contract_inputs"][
            "contract_tree_sha256"
        ],
        "invariant_pass_count": replay["coverage"]["invariant_pass_count"],
        "mutation_pass_count": replay["coverage"]["mutation_pass_count"],
        "structural_mutation_pass_count": replay["coverage"][
            "structural_mutation_pass_count"
        ],
        "all_pass": True,
        "generated_by_evaluated_system": True,
        "independent_review_eligible": False,
        "authority_granted": False,
    }


def _current_state(root: Path) -> dict[str, Any]:
    contract_root = root / validation.CONTRACT_ROOT
    schemas: dict[str, dict[str, Any]] = {}
    schema_hashes: dict[str, str] = {}
    schema_ids: dict[str, str] = {}
    schema_names = sorted(path.name for path in contract_root.glob("*.schema.json"))
    if not schema_names:
        raise ContractReconciliationError("current schema inventory is empty")
    for name in schema_names:
        raw = (contract_root / name).read_bytes()
        schema = _strict_object(raw, name)
        try:
            Draft202012Validator.check_schema(schema)
        except Exception as exc:  # jsonschema exposes several validation types.
            raise ContractReconciliationError(f"schema is invalid: {name}") from exc
        schema_id = schema.get("$id")
        if not isinstance(schema_id, str) or not schema_id:
            raise ContractReconciliationError(f"schema id is missing: {name}")
        schemas[name] = schema
        schema_hashes[name] = _sha256(raw)
        schema_ids[name] = schema_id
    if len(set(schema_ids.values())) != len(schema_ids):
        raise ContractReconciliationError("current schema ids are not unique")

    registry = Registry()
    for schema in schemas.values():
        registry = registry.with_resource(
            str(schema["$id"]), Resource.from_contents(schema)
        )
    example_hashes: dict[str, str] = {}
    example_replay: dict[str, Any] = {}
    for output, locator in validation.EXAMPLE_FILES.items():
        raw = (contract_root / locator).read_bytes()
        document = _strict_object(raw, locator)
        schema_name = validation.OUTPUT_SCHEMAS[output]
        errors = sorted(
            error.message
            for error in Draft202012Validator(
                schemas[schema_name], registry=registry
            ).iter_errors(document)
        )
        if errors:
            raise ContractReconciliationError(
                f"current example does not validate: {locator}"
            )
        example_hashes[locator] = _sha256(raw)
        example_replay[output] = {
            "example_locator": f"{validation.CONTRACT_ROOT.as_posix()}/{locator}",
            "schema_locator": (
                f"{validation.CONTRACT_ROOT.as_posix()}/{schema_name}"
            ),
            "structural_errors": 0,
            "passed": True,
        }

    trust_path = root / validation.CONTRACT_VALIDATION_TRUST_ROOT_PATH
    trust_raw = trust_path.read_bytes()
    trust = _strict_object(trust_raw, "active contract validation trust root")
    if (
        _sha256(trust_raw)
        != validation.EXPECTED_CONTRACT_VALIDATION_TRUST_ROOT_RAW_SHA256
        or canonical_sha256(trust)
        != validation.EXPECTED_CONTRACT_VALIDATION_TRUST_ROOT_OBJECT_SHA256
    ):
        raise ContractReconciliationError("active trust-root bytes drifted")

    semantic_raw = (root / validation.SEMANTIC_ARTIFACT_PATH).read_bytes()
    current_tree = validation._actual_contract_tree_sha256(root)
    current_content = validation._contract_content_sha256(
        root / validation.CONTRACT_PACK_ROOT
    )
    changed_runtime_schemas = sorted(
        name
        for name in validation.SCHEMA_FILES
        for digest in (schema_hashes[name],)
        if validation.EXPECTED_SCHEMA_SHA256.get(name) != digest
    )
    auxiliary_schemas = sorted(set(schema_names) - set(validation.SCHEMA_FILES))
    changed_examples = sorted(
        name
        for name, digest in example_hashes.items()
        if validation.EXPECTED_EXAMPLE_SHA256.get(name) != digest
    )
    reference_replay = _reference_semantic_replay(root)
    if reference_replay["contract_tree_sha256"] != current_tree:
        raise ContractReconciliationError(
            "reference semantic replay targets a different contract tree"
        )
    return {
        "active_trust_root": {
            "locator": validation.CONTRACT_VALIDATION_TRUST_ROOT_PATH.as_posix(),
            "raw_sha256": _sha256(trust_raw),
            "object_sha256": canonical_sha256(trust),
            "contract_tree_sha256": trust.get("contract_tree_sha256"),
            "production_model_authority": trust.get(
                "production_model_authority"
            ),
        },
        "current_contracts": {
            "contract_tree_sha256": current_tree,
            "contract_content_sha256": current_content,
            "schema_raw_sha256": dict(sorted(schema_hashes.items())),
            "schema_ids": dict(sorted(schema_ids.items())),
            "example_raw_sha256": dict(sorted(example_hashes.items())),
            "semantic_artifact_locator": validation.SEMANTIC_ARTIFACT_PATH.as_posix(),
            "semantic_artifact_raw_sha256": _sha256(semantic_raw),
        },
        "structural_replay": {
            "json_schema_dialect": "https://json-schema.org/draft/2020-12/schema",
            "schemas_checked": len(schemas),
            "schema_ids_unique": True,
            "examples_checked": len(example_replay),
            "examples": dict(sorted(example_replay.items())),
            "passed": True,
        },
        "reference_semantic_replay": reference_replay,
        "drift": {
            "contract_tree_changed": (
                current_tree != validation.CONTRACT_TREE_SHA256
            ),
            "contract_content_changed": (
                current_content != validation.EXPECTED_CONTRACT_CONTENT_SHA256
            ),
            "changed_runtime_schema_files": changed_runtime_schemas,
            "auxiliary_schema_files_without_individual_prior_hashes": (
                auxiliary_schemas
            ),
            "changed_example_files": changed_examples,
            "semantic_artifact_changed": (
                _sha256(semantic_raw)
                != validation.EXPECTED_SEMANTIC_ARTIFACT_SHA256
            ),
            "prior_contract_tree_bytes_available_in_candidate": False,
            "semantic_diff_review_complete": False,
            "candidate_anchor_semantic_harness_passed": True,
            "candidate_anchor_semantic_harness_independently_replayed": False,
        },
    }


def build_contract_reconciliation_candidate_v1(
    *,
    root: Path = ROOT,
    clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc),
) -> dict[str, Any]:
    state = _current_state(root)
    if not state["drift"]["contract_tree_changed"]:
        raise ContractReconciliationError("contract tree has no drift to reconcile")
    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "result_state": RESULT_STATE,
        "created_at_utc": _clock(clock).isoformat(),
        **state,
        "review_contract": {
            "registry_locator": REVIEW_REGISTRY_LOCATOR.as_posix(),
            "external_digest_environment": REVIEW_REGISTRY_ENV,
            "required_review_scopes": [
                "SCHEMA_SEMANTICS",
                "FAIL_CLOSED_AUTHORITY",
            ],
            "distinct_independent_reviewers_required": 2,
            "exact_prior_contract_tree_bytes_required": True,
            "candidate_anchor_semantic_harness_all_pass_required": True,
            "in_repository_reference_replay_is_non_independent": True,
            "review_must_not_be_generated_by_evaluated_system": True,
            "activation_requires_separate_no_clobber_trust_root_builder": True,
            "candidate_self_authorizing": False,
        },
        "decision": {
            "candidate_inventory_complete": True,
            "structural_replay_passed": True,
            "reference_semantic_replay_passed": True,
            "semantic_review_complete": False,
            "independent_review_present": False,
            "active_trust_root_changed": False,
            "activation_eligible": False,
        },
        "source_locks": [
            _source_record(root, SOURCE_LOCATOR),
            _source_record(root, VALIDATOR_SOURCE_LOCATOR),
            _source_record(root, REFERENCE_RUNNER_SOURCE_LOCATOR),
        ],
        "authority": dict(AUTHORITY),
        "claim_ceiling": CLAIM_CEILING,
    }
    payload["artifact_sha256"] = canonical_sha256(payload)
    return validate_contract_reconciliation_candidate_v1(payload, root=root)


def validate_contract_reconciliation_candidate_v1(
    payload: Mapping[str, Any], *, root: Path = ROOT
) -> dict[str, Any]:
    if not isinstance(payload, Mapping):
        raise ContractReconciliationError("candidate must be an object")
    value = dict(payload)
    expected_keys = {
        "schema_version",
        "result_state",
        "created_at_utc",
        "active_trust_root",
        "current_contracts",
        "structural_replay",
        "reference_semantic_replay",
        "drift",
        "review_contract",
        "decision",
        "source_locks",
        "authority",
        "claim_ceiling",
        "artifact_sha256",
    }
    if set(value) != expected_keys:
        raise ContractReconciliationError("candidate fields changed")
    if (
        value.get("schema_version") != SCHEMA_VERSION
        or value.get("result_state") != RESULT_STATE
    ):
        raise ContractReconciliationError("candidate identity changed")
    try:
        created = datetime.fromisoformat(
            str(value.get("created_at_utc")).replace("Z", "+00:00")
        )
    except ValueError as exc:
        raise ContractReconciliationError("candidate timestamp is invalid") from exc
    if created.tzinfo is None:
        raise ContractReconciliationError("candidate timestamp lacks timezone")
    unsigned = {key: item for key, item in value.items() if key != "artifact_sha256"}
    if value.get("artifact_sha256") != canonical_sha256(unsigned):
        raise ContractReconciliationError("candidate artifact hash changed")
    state = _current_state(root)
    for key in (
        "active_trust_root",
        "current_contracts",
        "structural_replay",
        "reference_semantic_replay",
        "drift",
    ):
        if value.get(key) != state[key]:
            raise ContractReconciliationError(f"candidate {key} drifted")
    expected_review = {
        "registry_locator": REVIEW_REGISTRY_LOCATOR.as_posix(),
        "external_digest_environment": REVIEW_REGISTRY_ENV,
        "required_review_scopes": [
            "SCHEMA_SEMANTICS",
            "FAIL_CLOSED_AUTHORITY",
        ],
        "distinct_independent_reviewers_required": 2,
        "exact_prior_contract_tree_bytes_required": True,
        "candidate_anchor_semantic_harness_all_pass_required": True,
        "in_repository_reference_replay_is_non_independent": True,
        "review_must_not_be_generated_by_evaluated_system": True,
        "activation_requires_separate_no_clobber_trust_root_builder": True,
        "candidate_self_authorizing": False,
    }
    if value.get("review_contract") != expected_review:
        raise ContractReconciliationError("candidate review contract changed")
    if value.get("decision") != {
        "candidate_inventory_complete": True,
        "structural_replay_passed": True,
        "reference_semantic_replay_passed": True,
        "semantic_review_complete": False,
        "independent_review_present": False,
        "active_trust_root_changed": False,
        "activation_eligible": False,
    }:
        raise ContractReconciliationError("candidate decision changed")
    if value.get("source_locks") != [
        _source_record(root, SOURCE_LOCATOR),
        _source_record(root, VALIDATOR_SOURCE_LOCATOR),
        _source_record(root, REFERENCE_RUNNER_SOURCE_LOCATOR),
    ]:
        raise ContractReconciliationError("candidate source locks changed")
    if value.get("authority") != AUTHORITY or any(value["authority"].values()):
        raise ContractReconciliationError("candidate exceeds authority")
    if value.get("claim_ceiling") != CLAIM_CEILING:
        raise ContractReconciliationError("candidate claim ceiling changed")
    return value


def write_contract_reconciliation_candidate_v1(
    *, root: Path = ROOT, output: Path = DEFAULT_OUTPUT
) -> Path:
    path = output if output.is_absolute() else root / output
    if path.exists():
        raise ContractReconciliationError(f"refusing to overwrite candidate: {path}")
    payload = build_contract_reconciliation_candidate_v1(root=root)
    raw = (
        json.dumps(payload, allow_nan=False, ensure_ascii=True, indent=2, sort_keys=True)
        + "\n"
    ).encode("ascii")
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".partial", dir=path.parent
    )
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        if path.exists():
            raise ContractReconciliationError(
                f"refusing to overwrite candidate: {path}"
            )
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.write:
            path = write_contract_reconciliation_candidate_v1(root=args.root)
            print(json.dumps({"output": str(path), "raw_sha256": _sha256(path.read_bytes())}, sort_keys=True))
        else:
            print(json.dumps(build_contract_reconciliation_candidate_v1(root=args.root), indent=2, sort_keys=True))
    except (OSError, ValueError, ContractReconciliationError) as exc:
        print(str(exc))
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


