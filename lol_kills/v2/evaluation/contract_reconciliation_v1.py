"""Build a non-authorizing candidate to reconcile drifted output contracts.

The active C0 trust root remains authoritative until a separate reviewer
registry supplies the exact prior schema bytes, replays the current semantic
harness against candidate anchors, and is pinned outside the repository.  This
module inventories current bytes and structural validity only; it cannot make
the current schemas trusted merely by hashing them.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import tempfile
from typing import Any, Callable, Mapping

from jsonschema import Draft202012Validator
